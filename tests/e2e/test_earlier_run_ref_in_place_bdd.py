"""E2E: `image i2i --ref <uuid>` of an image an EARLIER invocation made in the project (#995).

Binds ``tests/features/earlier_run_ref_in_place.feature``. Selected by ``-m e2e_image``;
see ``docs/E2E_TESTING.md`` § BDD-bound e2e.

**Why an e2e.** The in-place path (``MigratedComposer.reference_existing``) was proven
live only for an image the same process had just generated (#913). Whether an image from
an earlier process is still in the page's grid, offered by the ``@`` picker under the same
``/asb/<token>``, and carried by the submit Flow accepts, only a live run can show.

**Host-aware.** The seed and the i2i run in separate subprocesses, as in #995. The host
Flow served is read from the seed run's events (an i2i refused at $0 emits none):
``migrated.*`` events mean flow.google.com, where the contract is
``migrated.existing_references_attached`` naming the seed. Otherwise the labs contract
(``ui_automation_video.image_ref_selected_existing``) is asserted, so a labs-served run
is checked rather than skipped.

**Cost.** Two images of daily quota (seed + i2i), zero Veo credits. On a tree where the
i2i is refused (exit 36) only the seed is spent.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pytest_bdd import given, scenarios, then, when

from .test_image_uuid_ref_e2e import (
    _SELECTED_EXISTING_EVENT,
    _UPLOAD_FALLBACK_EVENT,
    _json_payload,
    _run_gflow,
)

scenarios("../features/earlier_run_ref_in_place.feature")

_ATTACHED_IN_PLACE = "migrated.existing_references_attached"
#: Every event that means bytes were uploaded, on either host.
_UPLOAD_EVENTS = {"migrated.frame_uploaded", "migrated.references_attached", _UPLOAD_FALLBACK_EVENT}


def _event_records(stderr: str) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    for line in stderr.splitlines():
        stripped = line.strip()
        if stripped.startswith("{"):
            try:
                records.append(dict(json.loads(stripped)))
            except json.JSONDecodeError:
                continue
    return records


@given("an image generated by an earlier gflow invocation in a project", target_fixture="world")
def _seed(e2e_env: dict[str, str], tmp_path: Path) -> dict[str, Any]:
    out = tmp_path / "out"
    seed = _run_gflow(
        [
            "image",
            "t2i",
            "a brass compass resting on an old sea chart",
            "--model",
            "nano2",
            "--project-name",
            "spike-995-e2e",
            "--out",
            str(out),
            "--json",
        ],
        e2e_env,
    )
    assert seed.returncode == 0, f"seed generation failed; stderr tail: {seed.stderr[-600:]!r}"
    payload = _json_payload(seed.stdout)
    images = payload.get("images") or []
    assert images, f"seed run returned no images: {payload}"
    project_id = str(payload.get("project_id") or "")
    assert project_id, f"seed payload carried no project_id: {payload}"
    # Read from the SEED, which always reaches a composer: an i2i refused before the page
    # (exit 36) emits no host event of its own.
    seed_events = {str(e.get("event", "")) for e in _event_records(seed.stderr)}
    host = "flow.google.com" if any(n.startswith("migrated.") for n in seed_events) else "labs"
    return {
        "host": host,
        "env": e2e_env,
        "out": out,
        "media_id": str(images[0]["media_name"]),
        "project_id": project_id,
    }


@when("a new invocation runs image i2i with that image's uuid as --ref in that project")
def _i2i(world: dict[str, Any]) -> None:
    proc = _run_gflow(
        [
            "image",
            "i2i",
            "the same compass, now under candlelight",
            "--ref",
            world["media_id"],
            "--project",
            world["project_id"],
            "--model",
            "nano2",
            "--out",
            str(world["out"]),
            "--json",
        ],
        world["env"],
    )
    world["proc"] = proc
    world["events"] = _event_records(proc.stderr)
    print(f"[995] host={world['host']} project={world['project_id']} media={world['media_id']}")


@then("the invocation succeeds and saves one image")
def _succeeds(world: dict[str, Any]) -> None:
    proc = world["proc"]
    assert proc.returncode == 0, (
        f"i2i of an earlier invocation's image in its own project failed on {world['host']} "
        f"(exit {proc.returncode}); stderr tail: {proc.stderr[-800:]!r}"
    )
    payload = _json_payload(proc.stdout)
    assert len(payload.get("images") or []) == 1, f"expected one image: {payload}"
    assert payload.get("ref_count") == 1, f"reference not counted: {payload}"


@then("the reference was attached in place, with no upload")
def _in_place(world: dict[str, Any]) -> None:
    events = world["events"]
    names = [str(e.get("event", "")) for e in events]
    uploads = sorted(_UPLOAD_EVENTS.intersection(names))
    assert not uploads, f"the reference was uploaded again on {world['host']}: {uploads}"
    if world["host"] == "flow.google.com":
        attached = [e for e in events if e.get("event") == _ATTACHED_IN_PLACE]
        assert attached, f"no {_ATTACHED_IN_PLACE}; observed: {sorted(set(names))}"
        assert list(attached[-1].get("media_ids") or []) == [world["media_id"]], attached[-1]
        # The exact-set submit guard is what proves no other media rode along.
        guarded = [e for e in events if e.get("event") == "migrated.image_submit_guarded"]
        assert guarded and guarded[-1].get("outcome") == "passed", guarded
        assert guarded[-1].get("body_media") == 1, guarded[-1]
    else:
        assert _SELECTED_EXISTING_EVENT in names, (
            f"labs: expected {_SELECTED_EXISTING_EVENT}; observed: {sorted(set(names))}"
        )
